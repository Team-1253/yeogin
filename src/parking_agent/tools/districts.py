def get_adjacent(district: str, count: int = 5) -> list[str]:
    """자치구와 인접 자치구 목록을 반환합니다.

    등록되지 않은 자치구는 빈 목록을 반환합니다.
    count로 반환 개수를 제한합니다.
    """
    if district not in SEOUL_DISTRICTS:
        return []
    return ADJACENT_DISTRICTS.get(district, [district])[:count]
